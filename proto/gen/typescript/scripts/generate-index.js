#!/usr/bin/env node
// Regenerates index.js and index.d.ts by namespacing every package directory
// under src/ that contains *_pb.js files.
//
//   src/iroh/v1/*_pb.js      -> export * as irohV1 from "./namespaces/irohV1.js"
//   src/services/v1/*_pb.js  -> export * as servicesV1 from "./namespaces/servicesV1.js"
//
// Each namespace is a small barrel in namespaces/ that re-exports every
// *_pb file of that directory, so same-named exports in different packages
// (e.g. DeviceService) never collide: irohV1.DeviceService vs servicesV1.DeviceService.
//
// Run automatically as part of `pnpm build`/`pnpm dev`, or directly via
// `pnpm run generate`.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = fileURLToPath(new URL("..", import.meta.url));
const srcDir = join(rootDir, "src");
const nsDir = join(rootDir, "namespaces");

function findPbFiles(dir) {
  const results = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findPbFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith("_pb.js")) {
      results.push(fullPath);
    }
  }
  return results;
}

const files = findPbFiles(srcDir).sort();
if (files.length === 0) {
  throw new Error(`No *_pb.js files found under ${srcDir}`);
}

// "src/iroh/v1" -> "irohV1", "src/my_pkg/v2" -> "myPkgV2"
function namespaceName(dir) {
  const parts = relative(srcDir, dir)
    .split(sep)
    .flatMap((p) => p.split(/[^A-Za-z0-9]+/))
    .filter(Boolean);
  return parts
    .map((p, i) => (i === 0 ? p[0].toLowerCase() : p[0].toUpperCase()) + p.slice(1))
    .join("");
}

// Group files by directory (one directory = one proto package/version).
const groups = new Map();
for (const file of files) {
  const dir = dirname(file);
  groups.set(dir, [...(groups.get(dir) ?? []), file]);
}

// Make sure two directories never map to the same namespace name.
const names = new Map();
for (const dir of groups.keys()) {
  const name = namespaceName(dir);
  if (names.has(name)) {
    throw new Error(
      `Namespace "${name}" is produced by both ${names.get(name)} and ${dir}`,
    );
  }
  names.set(name, dir);
}

const banner = "// AUTO-GENERATED by scripts/generate-index.js — do not edit by hand\n";
const posix = (p) => p.split(sep).join("/");

// Rebuild barrels from scratch so removed packages don't leave stale files.
rmSync(nsDir, { recursive: true, force: true });
mkdirSync(nsDir, { recursive: true });

for (const [name, dir] of names) {
  const lines = groups
    .get(dir)
    .map((f) => `export * from "${"../" + posix(relative(rootDir, f))}";`);
  const contents = banner + lines.join("\n") + "\n";
  writeFileSync(join(nsDir, `${name}.js`), contents);
  writeFileSync(join(nsDir, `${name}.d.ts`), contents);
}

const body =
  [...names.keys()]
    .sort()
    .map((name) => `export * as ${name} from "./namespaces/${name}.js";`)
    .join("\n") + "\n";
const contents = banner + body;

writeFileSync(join(rootDir, "index.js"), contents);
writeFileSync(join(rootDir, "index.d.ts"), contents);

console.log(
  `generate-index: wrote index.js/index.d.ts with ${names.size} namespace(s): ${[...names.keys()].sort().join(", ")}.`,
);